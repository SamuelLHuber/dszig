    var low: usize = 0;
    var high: usize = nonprintable.len;
    while (low < high) {
        const middle = low + (high - low) / 2;
        const range = nonprintable[middle];
        if (codepoint < range.first) {
            high = middle;
        } else if (codepoint > range.last) {
            low = middle + 1;
        } else {
            return false;
        }
    }
    return true;
}


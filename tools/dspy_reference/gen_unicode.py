"""Unicode tables for normalize_text and Pydantic titles, from CPython 3.11.

DSPy's `normalize_text` runs `unicodedata.normalize("NFD", s)`, `str.lower`,
`re.sub(r"\\b(a|an|the)\\b", ...)` and `str.split`. Pydantic schema titles
also use `str.title`. Every table here is
derived by asking Python how those calls treat each code point, so DSZig
reproduces them exactly (Unicode 14.0.0).

Usage: uv run gen_unicode.py [out_dir]  (default: ../../src)"""

import pathlib
import re
import sys
import unicodedata

CODEPOINTS = [cp for cp in range(sys.maxunicode + 1) if not 0xD800 <= cp <= 0xDFFF]
HANGUL = range(0xAC00, 0xD7A4)
SIGMA = "\u03a3"
WORD = re.compile(r"\w")


def ranges(pred):
    out = []
    for cp in CODEPOINTS:
        if not pred(cp):
            continue
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def class_ranges():
    out = []
    for cp in CODEPOINTS:
        ccc = unicodedata.combining(chr(cp))
        if not ccc:
            continue
        if out and out[-1][1] == cp - 1 and out[-1][2] == ccc:
            out[-1][1] = cp
        else:
            out.append([cp, cp, ccc])
    return out


def mappings(fn):
    pool, table = [], []
    for cp in CODEPOINTS:
        mapped = fn(chr(cp))
        if mapped == chr(cp):
            continue
        table.append((cp, len(pool), len(mapped)))
        pool.extend(ord(c) for c in mapped)
    return pool, table


def final_sigma(s):
    return s.lower()[-1] == "\u03c2"


def case_ignorable(cp):
    # "A" X "Σ" ends in ς iff X is case-ignorable or cased; " " X "Σ" iff X
    # is cased and not case-ignorable (CPython's handle_capital_sigma).
    x = chr(cp)
    return final_sigma("A" + x + SIGMA) and not final_sigma(" " + x + SIGMA)


def cased(cp):
    return final_sigma(" " + chr(cp) + SIGMA)


def emit_ranges(lines, name, rs):
    lines.append(f"pub const {name} = [_]Range{{")
    lines.extend(f"    .{{ .lo = 0x{lo:x}, .hi = 0x{hi:x} }}," for lo, hi in rs)
    lines.append("};")


def emit_mapping(lines, name, pool, table):
    lines.append(f"pub const {name}_pool = [_]u21{{")
    lines.extend(f"    0x{cp:x}," for cp in pool)
    lines.append("};")
    lines.append(f"pub const {name} = [_]Mapping{{")
    lines.extend(f"    .{{ .cp = 0x{cp:x}, .start = {start}, .len = {n} }}," for cp, start, n in table)
    lines.append("};")


def main():
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[2] / "src"
    out.mkdir(parents=True, exist_ok=True)
    nfd_pool, nfd = mappings(lambda c: c if ord(c) in HANGUL else unicodedata.normalize("NFD", c))
    lower_pool, lower = mappings(lambda c: c if c == SIGMA else c.lower())
    title_pool, title = mappings(str.title)
    lines = [
        f"//! Generated by tools/dspy_reference/gen_unicode.py from CPython 3.11's",
        f"//! unicodedata (Unicode {unicodedata.unidata_version}), str.lower/title, re's \\w and str.split. Do not edit.",
        "",
        "pub const Range = struct { lo: u21, hi: u21 };",
        "pub const ClassRange = struct { lo: u21, hi: u21, ccc: u8 };",
        "pub const Mapping = struct { cp: u21, start: u16, len: u8 };",
        "",
        "/// Full canonical decomposition (Hangul syllables are algorithmic).",
    ]
    emit_mapping(lines, "nfd", nfd_pool, nfd)
    lines.append("/// `str.lower` per code point, except Σ (final-sigma rule).")
    emit_mapping(lines, "lower", lower_pool, lower)
    lines.append("/// `str.title` per code point.")
    emit_mapping(lines, "title", title_pool, title)
    lines.append("/// Cased characters for str.title, including case-ignorable cased characters.")
    emit_ranges(lines, "title_cased", ranges(lambda cp: chr(cp).islower() or chr(cp).isupper() or chr(cp).istitle()))
    lines.append("/// Canonical combining classes.")
    lines.append("pub const ccc = [_]ClassRange{")
    lines.extend(f"    .{{ .lo = 0x{lo:x}, .hi = 0x{hi:x}, .ccc = {c} }}," for lo, hi, c in class_ranges())
    lines.append("};")
    lines.append("/// Cased and not case-ignorable, as seen by the final-sigma rule.")
    emit_ranges(lines, "cased", ranges(cased))
    emit_ranges(lines, "case_ignorable", ranges(case_ignorable))
    lines.append("/// `re.match(r\"\\w\", c)`.")
    emit_ranges(lines, "word", ranges(lambda cp: WORD.match(chr(cp)) is not None))
    lines.append("/// `str.split()` separators.")
    emit_ranges(lines, "space", ranges(lambda cp: ("a" + chr(cp) + "b").split() == ["a", "b"]))
    (out / "unicode_tables.zig").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()

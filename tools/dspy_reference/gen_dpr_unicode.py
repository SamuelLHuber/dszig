"""Character classes for DSPy's DPR SimpleTokenizer, read from pinned regex.

DSPy compiles `([\\p{L}\\p{N}\\p{M}]+)|([^\\p{Z}\\p{C}])` with
IGNORECASE|UNICODE|MULTILINE. Each scalar value, including lone surrogates,
is classified by asking that exact compiled expression which group matches it.
The installed regex package's Unicode data can differ from CPython's
unicodedata, so no category table is derived from unicodedata.

Usage: .venv/bin/python gen_dpr_unicode.py [--check] [out_file]
(default: ../../src/dpr_unicode.zig)"""

import hashlib
import importlib.metadata
import pathlib
import sys

import regex

from dspy.dsp.utils.dpr import SimpleTokenizer

PATTERN = SimpleTokenizer()._regexp
EXPECTED_PATTERN = r"([\p{L}\p{N}\p{M}]+)|([^\p{Z}\p{C}])"
EXPECTED_FLAGS = regex.IGNORECASE | regex.UNICODE | regex.MULTILINE


def regex_unicode_version():
    description = importlib.metadata.metadata("regex").get_payload()
    match = regex.search(r"This module supports Unicode ([0-9.]+)\.", description)
    assert match is not None
    return match.group(1)


def classify(cp):
    match = PATTERN.fullmatch(chr(cp))
    if match is None:
        return 0
    if match.lastindex == 1:
        return 1
    assert match.lastindex == 2
    return 2


def ranges(classes, kind):
    out = []
    for cp, value in enumerate(classes):
        if value != kind:
            continue
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def emit_ranges(lines, name, rs):
    lines.append(f"pub const {name} = [_]Range{{")
    lines.extend(f"    .{{ .lo = 0x{lo:x}, .hi = 0x{hi:x} }}," for lo, hi in rs)
    lines.append("};")


def render():
    assert PATTERN.pattern == EXPECTED_PATTERN
    assert PATTERN.flags & EXPECTED_FLAGS == EXPECTED_FLAGS
    classes = bytes(classify(cp) for cp in range(sys.maxunicode + 1))
    digest = hashlib.sha256(classes).hexdigest()
    word = ranges(classes, 1)
    other = ranges(classes, 2)
    lines = [
        "//! Generated by tools/dspy_reference/gen_dpr_unicode.py. Do not edit.",
        f"//! Source: DSPy {importlib.metadata.version('dspy')} SimpleTokenizer, regex {importlib.metadata.version('regex')}",
        f"//! (package metadata: Unicode {regex_unicode_version()}), Python {sys.version.split()[0]}.",
        f"//! Pattern: {EXPECTED_PATTERN} with IGNORECASE|UNICODE|MULTILINE.",
        f"//! Classes for U+0000..U+10FFFF as bytes (0 excluded, 1 word, 2 other) SHA256 {digest}.",
        "",
        "pub const Range = struct { lo: u21, hi: u21 };",
        "",
        "/// Scalar values matched by the first alternative.",
    ]
    emit_ranges(lines, "word", word)
    lines.append("/// Scalar values matched only by the single-character second alternative.")
    emit_ranges(lines, "other", other)
    return "\n".join(lines) + "\n", digest, len(word), len(other)


def main():
    args = sys.argv[1:]
    check = bool(args) and args[0] == "--check"
    if check:
        args = args[1:]
    out = pathlib.Path(args[0]) if args else pathlib.Path(__file__).resolve().parents[2] / "src" / "dpr_unicode.zig"
    text, digest, word_count, other_count = render()
    if check:
        if out.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{out} is stale")
    else:
        out.write_text(text, encoding="utf-8")
    print(f"sha256={digest} word_ranges={word_count} other_ranges={other_count}")


if __name__ == "__main__":
    main()
